#!/usr/bin/env python3
"""Check that Markdown links in the repository resolve, and that every doc is reachable.

Checks every tracked (and untracked, not ignored) *.md file outside docs/archive/, the
generated Laravel Boost skills and the docs site's pages (apps/docs, checked by its own
build):

- relative links and images point at files that exist inside the repository;
- #anchors into Markdown files match a heading, using GitHub's slug rules (lower case,
  punctuation such as dots dropped, spaces to hyphens, -1/-2 for repeats);
- every docs/**/*.md outside the archive is reachable from docs/README.md.

External links (http:, mailto:, ...) are not fetched. In-product help links
(/help/<slug> inside apps/api/resources/help) are app routes, not repository paths.

Usage: python tooling/docs/check_links.py [--root <repository>]
"""
import argparse
import os
import re
import subprocess
import sys
import unicodedata
from collections import deque
from urllib.parse import unquote

SKIP_PREFIXES = (
    "docs/archive/",  # historical record, kept unmaintained on purpose
    "apps/api/.agents/",  # generated by Laravel Boost
    "apps/api/.claude/",
    # Docs site pages link to site routes (/docs/...), not repository paths;
    # starlight-links-validator and check-docs `features` check them in the docs build.
    "apps/docs/src/content/",
)
FENCE = re.compile(r"^(```|~~~)")
INLINE_CODE = re.compile(r"`+[^`]*`+")
LINK = re.compile(r"(?<!\!)\[(?:[^\[\]]|\[[^\]]*\])*\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)")
IMAGE = re.compile(r"!\[[^\]]*\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)")
REFDEF = re.compile(r"^\s{0,3}\[[^\]]+\]:\s*<?(\S+?)>?(?:\s|$)")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
HTML_ID = re.compile(r"<a\s+(?:name|id)=\"([^\"]+)\"")
EXTERNAL = re.compile(r"^[a-z][a-z0-9+.-]*:", re.I)


def slugify(text):
    """GitHub's heading anchor: drop markup and punctuation, keep letters, digits, - and _."""
    text = re.sub(r"<[^>]+>", "", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = text.replace("`", "").strip().lower()
    kept = (ch for ch in text if ch in " -_" or unicodedata.category(ch)[0] in "LN")
    return "".join(kept).replace(" ", "-")


def markdown_lines(path):
    """Yield (line number, line) outside fenced code blocks."""
    in_fence = False
    with open(path, encoding="utf-8") as stream:
        for number, line in enumerate(stream, 1):
            if FENCE.match(line.strip()):
                in_fence = not in_fence
                continue
            if not in_fence:
                yield number, line


class Checker:
    def __init__(self, root):
        self.root = os.path.realpath(root)
        self.anchor_cache = {}
        self.errors = []
        self.graph = {}

    def markdown_files(self):
        listed = subprocess.run(
            ["git", "-C", self.root, "ls-files", "--cached", "--others", "--exclude-standard", "--", "*.md"],
            check=True, capture_output=True, text=True,
        ).stdout.split()
        return sorted(
            rel for rel in listed
            if os.path.exists(os.path.join(self.root, rel))
            and "node_modules/" not in rel
            and not rel.startswith(SKIP_PREFIXES)
        )

    def anchors(self, path):
        if path not in self.anchor_cache:
            found, repeats = set(), {}
            for _, line in markdown_lines(path):
                found.update(HTML_ID.findall(line))
                heading = HEADING.match(line)
                if heading:
                    slug = slugify(heading.group(2))
                    count = repeats.get(slug, 0)
                    found.add(slug if count == 0 else f"{slug}-{count}")
                    repeats[slug] = count + 1
            self.anchor_cache[path] = found
        return self.anchor_cache[path]

    def check_file(self, rel):
        path = os.path.join(self.root, rel)
        self.graph[rel] = set()
        for number, line in markdown_lines(path):
            text = INLINE_CODE.sub("", line)
            for pattern in (LINK, IMAGE, REFDEF):
                for match in pattern.finditer(text):
                    self.check_link(rel, path, number, match.group(1))

    def check_link(self, rel, path, number, target):
        if EXTERNAL.match(target) or target.startswith("//"):
            return
        if rel.startswith("apps/api/resources/help/") and target.startswith("/help/"):
            return
        target_path, _, fragment = target.partition("#")
        target_path = unquote(target_path)
        if not target_path:
            resolved = path
        elif target_path.startswith("/"):
            resolved = os.path.join(self.root, target_path.lstrip("/"))
        else:
            resolved = os.path.normpath(os.path.join(os.path.dirname(path), target_path))
        if not os.path.realpath(resolved).startswith(self.root + os.sep) and os.path.realpath(resolved) != self.root:
            self.errors.append(f"{rel}:{number}: link leaves the repository: {target}")
            return
        if not os.path.exists(resolved):
            self.errors.append(f"{rel}:{number}: missing target {target}")
            return
        if resolved.endswith(".md"):
            self.graph[rel].add(os.path.relpath(resolved, self.root))
            if fragment and unquote(fragment) not in self.anchors(resolved):
                self.errors.append(f"{rel}:{number}: no heading for #{fragment} in {os.path.relpath(resolved, self.root)}")

    def orphans(self, checked):
        docs = {rel for rel in checked if rel.startswith("docs/")}
        if "docs/README.md" not in docs:
            return []
        seen, queue = set(), deque(["docs/README.md"])
        while queue:
            node = queue.popleft()
            if node not in seen:
                seen.add(node)
                queue.extend(target for target in self.graph.get(node, ()) if target in docs)
        return sorted(docs - seen)

    def run(self):
        checked = self.markdown_files()
        for rel in checked:
            self.check_file(rel)
        orphans = self.orphans(checked)
        return checked, orphans


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
    args = parser.parse_args(argv)
    checker = Checker(args.root)
    checked, orphans = checker.run()
    for error in checker.errors:
        print("FAIL", error)
    for orphan in orphans:
        print("FAIL", f"{orphan}: not reachable from docs/README.md")
    status = "FAIL" if checker.errors or orphans else "PASS"
    print(f"{status} {len(checked)} Markdown files, {len(checker.errors)} broken link(s), {len(orphans)} unreachable doc(s)")
    return 1 if checker.errors or orphans else 0


if __name__ == "__main__":
    sys.exit(main())
