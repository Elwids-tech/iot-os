// Verify the rebuilt portal with an isolated local fixture and local webhook sink.
import {createRequire} from 'node:module'
import {readFile} from 'node:fs/promises'
import assert from 'node:assert/strict'
const require=createRequire(new URL('../apps/portal/package.json',import.meta.url))
const {chromium,expect}=require('@playwright/test')
const fixture=JSON.parse(await readFile('/tmp/iot-sdk-fixture.json','utf8'))
const origin='http://localhost:8001'
const browser=await chromium.launch({headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1000}})
const page=await context.newPage()
page.setDefaultTimeout(10000)
const errors=[];page.on('pageerror',error=>errors.push(error.message))
await page.route(origin+'/api/**',async route=>route.continue({headers:{...route.request().headers(),Authorization:'Bearer '+fixture.adminToken}}))
async function confirm(name){await page.getByRole('alertdialog').getByRole('button',{name,exact:true}).click()}
try{
 await page.goto('http://localhost:5173/organizations/'+fixture.organization+'/integrations')
 await page.getByRole('button',{name:'Create application',exact:true}).click()
 await page.getByLabel('Application name').fill('Temporary UI verification')
 for(const name of ['Device details','Telemetry and location','Alerts','Alert event feed'])await page.getByRole('checkbox',{name,exact:true}).check()
 await page.getByRole('combobox',{name:'Add a device'}).click()
 await page.getByRole('option',{name:'SDK fixture one · one'}).click()
 await page.getByRole('button',{name:'Save application',exact:true}).click()
 await page.getByRole('link',{name:'Temporary UI verification',exact:true}).click()
 await page.getByRole('button',{name:'Issue new token'}).click();await confirm('Issue token')
 const token=await page.getByLabel('Application token value').inputValue()
 const read=()=>fetch(origin+'/api/integration/v1/organizations/'+fixture.organization+'/devices',{headers:{Accept:'application/json',Authorization:'Bearer '+token}})
 assert.equal((await read()).status,200)
 await page.getByRole('button',{name:"I've stored it"}).click()
 await page.getByLabel('Receiver URL').fill('http://webhook-sink:8080/events')
 await page.getByRole('button',{name:'Configure / rotate key'}).click();await confirm('Configure webhook')
 await expect(page.getByLabel('Webhook signing secret value')).toBeVisible()
 await page.getByRole('button',{name:"I've stored it"}).click()
 const acknowledged=await fetch(origin+'/api/v1/organizations/'+fixture.organization+'/alerts/'+fixture.alert+'/acknowledge',{method:'POST',headers:{Accept:'application/json','Content-Type':'application/json',Authorization:'Bearer '+fixture.adminToken},body:'{}'})
 assert.equal(acknowledged.status,200)
 await expect(page.getByText('delivered',{exact:true})).toBeVisible({timeout:45000})
 await page.getByText('Attempt history',{exact:true}).click()
 await expect(page.getByText(/HTTP 503/)).toBeVisible();await expect(page.getByText(/HTTP 204/)).toBeVisible()
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:'/tmp/iot-integrations-desktop.png',fullPage:true})
 await page.getByRole('button',{name:'Disable webhook',exact:true}).click();await confirm('Disable webhook')
 await expect(page.getByText('Webhook disabled.',{exact:true}).first()).toBeVisible()
 await page.getByLabel('Application name').fill('Temporary updated integration')
 await page.getByRole('button',{name:'Save grants',exact:true}).click();await confirm('Save grants')
 await expect(page.getByRole('heading',{name:'Temporary updated integration',exact:true})).toBeVisible()
 assert.equal((await read()).status,401)
 await page.getByRole('button',{name:'Revoke application',exact:true}).click();await confirm('Revoke application')
 await expect(page.getByRole('button',{name:'Issue new token'})).toBeDisabled()
 assert.deepEqual(errors,[])
 console.log('PASS rebuilt portal: create all grants, searchable device selection, live token, webhook secret and 503/204 delivery history, disable, grant invalidation and revoke.')
}finally{await context.close();await browser.close()}
