<?php

declare(strict_types=1);

namespace App\Domain\Firmware\Services;

use App\Domain\Devices\Models\Device;
use App\Domain\Devices\Models\DeviceOnboarding;
use App\Domain\Devices\Models\SparkplugGateway;
use App\Domain\Devices\Services\BrokerProvisioner;
use App\Domain\Devices\Services\DeviceConnectionKit;

/**
 * Connection settings for one direct device or gateway (spec 027 R4): config/iotos_settings.h
 * and .c, config/README.md and, for a direct device, today's three kit files. The only class
 * that reads credentials for firmware downloads.
 */
final class ConnectionSettings
{
    public function __construct(
        private readonly DeviceConnectionKit $kit,
        private readonly BrokerProvisioner $provisioner,
        private readonly MetricTables $tables,
        private readonly StarterBuilder $starters,
    ) {}

    /** @return array<string, string> archive path => contents */
    public function device(Device $device): array
    {
        $setup = DeviceOnboarding::where('device_id', $device->id)->first();
        abort_unless($setup?->mode === 'direct', 422, 'Only a device that connects directly has its own connection settings. A device behind a gateway uses the gateway\'s.');
        $files = $this->kit->files($setup); // provisioned, not archived, public endpoint and CA
        $endpoint = $this->kit->endpoint();
        $gateway = $setup->gateway;

        return [...$this->render([
            'subject' => 'device "'.$device->name.'"', 'host' => $endpoint['host'], 'port' => $endpoint['port'],
            'group_id' => $gateway->connection->group_id, 'edge_node_id' => $gateway->edge_node_id, 'host_id' => $gateway->connection->host_id,
            'username' => $gateway->username, 'password' => $gateway->password, 'ca' => $endpoint['ca'], 'gateway' => false,
        ]), ...$files];
    }

    /** @return array<string, string> archive path => contents */
    public function gateway(SparkplugGateway $gateway): array
    {
        abort_unless($gateway->username && $gateway->password, 422, 'This gateway has no platform-issued credentials.');
        abort_unless($gateway->connection?->status === 'ready', 422, 'Provision this gateway\'s connection first.');
        $endpoint = $this->kit->endpoint();
        // The same idempotent broker access as POST gateways/{gateway}/provision, so the settings work.
        $this->provisioner->gateway($gateway);

        return $this->render([
            'subject' => 'gateway "'.$gateway->name.'"', 'host' => $endpoint['host'], 'port' => $endpoint['port'],
            'group_id' => $gateway->connection->group_id, 'edge_node_id' => $gateway->edge_node_id, 'host_id' => $gateway->connection->host_id,
            'username' => $gateway->username, 'password' => $gateway->password, 'ca' => $endpoint['ca'], 'gateway' => true,
        ]);
    }

    /**
     * The settings files from their values. Pure, so golden copies can be rendered from
     * fixture credentials.
     *
     * @param  array{subject: string, host: string, port: int, group_id: string, edge_node_id: string, host_id: string, username: string, password: string, ca: string, gateway: bool}  $values
     * @return array<string, string>
     */
    public function render(array $values): array
    {
        // One string per PEM line, each ending in an escaped newline.
        $ca = array_map(fn (string $line): string => '    '.substr($this->tables->string($line), 0, -1).'\\n"', preg_split('/\r?\n/', trim($values['ca'])));
        $header = implode("\n", [
            '/* Generated by IoT OS for '.$this->tables->comment($values['subject']).'. Keep it private: it lets this one',
            ' * '.($values['gateway'] ? 'gateway' : 'device').' connect as itself. See config/README.md. */',
            '#ifndef IOTOS_KIT_SETTINGS_H',
            '#define IOTOS_KIT_SETTINGS_H',
            '',
            '#include "iotos/iotos.h"',
            '',
            '#define IOTOS_KIT_SETTINGS_FORMAT 1 /* starters refuse other formats */',
            '#define IOTOS_KIT_BROKER_HOST '.$this->tables->string($values['host']),
            '#define IOTOS_KIT_BROKER_PORT '.(int) $values['port'],
            '#define IOTOS_KIT_GROUP_ID '.$this->tables->string($values['group_id']),
            '#define IOTOS_KIT_EDGE_NODE_ID '.$this->tables->string($values['edge_node_id']),
            '#define IOTOS_KIT_HOST_ID '.$this->tables->string($values['host_id']),
            '#define IOTOS_KIT_USERNAME '.$this->tables->string($values['username']).' /* also the MQTT client ID */',
            '#define IOTOS_KIT_PASSWORD '.$this->tables->string($values['password']),
            '#define IOTOS_KIT_CA_PEM \\',
            implode(" \\\n", $ca),
            '#define IOTOS_KIT_GATEWAY '.($values['gateway'] ? '1 /* 0 for a direct device */' : '0 /* 1 for a gateway */'),
            '',
            '/* node_type is NULL: the program copies these settings and sets it from generated/. */',
            'extern const iotos_settings iotos_kit_settings;',
            'extern const int iotos_kit_settings_present;',
            '',
            '#endif',
        ])."\n";
        $source = implode("\n", [
            '/* Generated by IoT OS. Keep it private. */',
            '#include "iotos_settings.h"',
            '',
            'const iotos_settings iotos_kit_settings = {',
            '    IOTOS_KIT_BROKER_HOST, IOTOS_KIT_BROKER_PORT, IOTOS_KIT_GROUP_ID, IOTOS_KIT_EDGE_NODE_ID,',
            '    IOTOS_KIT_HOST_ID,     IOTOS_KIT_USERNAME,    IOTOS_KIT_PASSWORD, IOTOS_KIT_CA_PEM,',
            '    NULL,',
            '};',
            'const int iotos_kit_settings_present = 1;',
        ])."\n";

        return [
            'config/README.md' => $this->starters->configReadme(),
            'config/iotos_settings.c' => $source,
            'config/iotos_settings.h' => $header,
        ];
    }
}
