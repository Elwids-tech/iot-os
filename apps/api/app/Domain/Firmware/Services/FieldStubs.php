<?php

declare(strict_types=1);

namespace App\Domain\Firmware\Services;

/**
 * The developer's starting point (spec 027 R9): field.h and field.c with one read stub per
 * metric and one command stub per writable metric, and an annotated device brief. No stub
 * returns a value, so a starter publishes nothing until the field side is written.
 */
final class FieldStubs
{
    private const MEMBERS = [
        'Boolean' => 'as.boolean', 'Int64' => 'as.i64', 'Double' => 'as.number', 'String' => 'as.string',
        'DateTime' => 'as.utc_ms', 'Bytes' => 'as.bytes',
    ];

    public function __construct(private readonly MetricTables $tables) {}

    /**
     * @param  array  $node  the node type (MetricTables shape)
     * @param  list<array>  $types  downstream types, empty for a direct device
     * @return array<string, string> file name => contents
     */
    public function files(array $node, array $types, bool $gateway): array
    {
        $sections = $this->sections($node, $types, $gateway);

        return [
            'field.h' => $this->header($sections, $gateway),
            'field.c' => $this->source($sections, $types, $gateway),
            'device-brief.example.yaml' => $this->brief($sections, $gateway),
        ];
    }

    /** Each type the developer writes code for, with its metrics and their function names. */
    private function sections(array $node, array $types, bool $gateway): array
    {
        $sections = $used = [];
        $healthKeys = $gateway ? $this->tables->healthKeys() : [];
        foreach ([$node, ...$types] as $index => $type) {
            $isNode = $index === 0;
            $metrics = array_values(array_filter($type['metrics'], fn (array $metric): bool => ! ($isNode && in_array($metric['key'], $healthKeys, true))));
            if ($metrics === [] && ($isNode && $gateway)) {
                continue; // the SDK fills every metric of the gateway's own type
            }
            foreach ($metrics as $i => $metric) {
                // Function names are unique across every type: a clash gets a numeric suffix.
                $base = $name = $type['c_identifier'].'_'.$this->tables->slug($metric['key']);
                for ($n = 2; isset($used[$name]); $n++) {
                    $name = $base.'_'.$n;
                }
                $used[$name] = true;
                $metrics[$i]['function'] = $name;
            }
            $sections[] = ['type' => $type, 'node' => $isNode, 'metrics' => $metrics];
        }

        return $sections;
    }

    private function title(array $section, bool $gateway): string
    {
        $type = $section['type'];
        $what = $section['node'] ? ($gateway ? 'this gateway\'s own metrics' : 'this device') : 'devices behind this gateway';

        return $this->tables->comment($type['name'].' ('.$type['code'].'), revision '.$type['revision'].': '.$what);
    }

    private function header(array $sections, bool $gateway): string
    {
        $lines = [
            '/*',
            ' * The field side\'s interface, generated by IoT OS for '.($gateway ? 'a gateway' : 'a direct device').'.',
            ' * Yours from now on: updates never replace it.',
            ' */',
            '#ifndef FIELD_H',
            '#define FIELD_H',
            '',
            '#include <stddef.h>',
            '',
            '#include "iotos/iotos.h"',
            '',
            'typedef enum {',
            '    FIELD_OK = 0,          /* the value was read, or the command was applied */',
            '    FIELD_UNAVAILABLE = 1, /* no value now: the metric is left out, and births send a null */',
            '    FIELD_OFFLINE = 2,     /* the device did not answer */',
            '    FIELD_REJECTED = 3     /* the command was not applied */',
            '} field_status;',
            '',
            '/* A device behind the gateway: its ID (at most IOTOS_DEVICE_ID_MAX characters, unique on',
            ' * this gateway) and the code of its type in iotos_kit_types. */',
            'typedef struct {',
            '    const char *id;',
            '    const char *type;',
            '} field_device;',
            '',
            'extern const field_device field_devices[];',
            'extern const size_t field_device_count;',
            '',
            '/* Called once before connecting: open buses and ports here. Returns 0 on success. */',
            'int field_init(void);',
            '',
            '/* Called by main.c for each metric. out->datatype is already set: fill the matching member',
            ' * of out->as. type is a type\'s code, metric a metric\'s name, device_id NULL for the node. */',
            'field_status field_read(const char *type, const char *metric, const char *device_id, iotos_value *out);',
            '',
            '/* Called with a validated command. Apply it and return FIELD_OK: main.c then reads the',
            ' * metric back with field_read and publishes it, which is how the platform confirms it. */',
            'field_status field_command(const char *type, const char *metric, const char *device_id, const iotos_value *value);',
        ];
        foreach ($sections as $section) {
            $lines[] = '';
            $lines[] = '/* '.$this->title($section, $gateway).' */';
            foreach ($section['metrics'] as $metric) {
                $lines[] = 'field_status field_read_'.$metric['function'].'(const char *device_id, iotos_value *out);';
                if ($metric['writable']) {
                    $lines[] = 'field_status field_command_'.$metric['function'].'(const char *device_id, const iotos_value *value);';
                }
            }
        }
        $lines[] = '';
        $lines[] = '#endif';

        return implode("\n", $lines)."\n";
    }

    private function source(array $sections, array $types, bool $gateway): string
    {
        $codes = implode(', ', array_map(fn ($type) => $type['code'], $types));
        $example = $types === [] ? '' : ' for example {"'.$this->example($types[0]).'", "'.$types[0]['code'].'"}.';
        $lines = [
            '/*',
            ' * The field side: how each metric is read from the hardware and how each command is applied,',
            ' * written from device-brief.yaml. Generated as stubs: every read returns FIELD_UNAVAILABLE',
            ' * and every command FIELD_REJECTED, so nothing is published until it is implemented. Never',
            ' * return a value that was not read from the device.',
            ' *',
            ' * Yours from now on: updates never replace it. A newer starter\'s field.c has the stubs for',
            ' * metrics added since; copy the ones you need.',
            ' */',
            '#include "field.h"',
            '',
            '#include <string.h>',
            '',
        ];
        if ($gateway) {
            $lines[] = '/* The devices behind this gateway, from the device brief\'s addressing. Add each one above';
            $lines[] = ' * the end marker,'.$this->tables->comment($example).' Types: '.$this->tables->comment($codes).'. */';
        } else {
            $lines[] = '/* A direct device has no devices behind it: it publishes its own metrics. */';
        }
        $lines[] = 'const field_device field_devices[] = {';
        $lines[] = '    {NULL, NULL} /* end of the list */';
        $lines[] = '};';
        $lines[] = 'const size_t field_device_count = sizeof(field_devices) / sizeof(field_devices[0]) - 1;';
        $lines[] = '';
        $lines[] = 'int field_init(void)';
        $lines[] = '{';
        $lines[] = '    return 0;';
        $lines[] = '}';
        foreach ($sections as $section) {
            $lines[] = '';
            $lines[] = '/* '.$this->title($section, $gateway).' */';
            foreach ($section['metrics'] as $metric) {
                $lines[] = '';
                $lines[] = 'field_status field_read_'.$metric['function'].'(const char *device_id, iotos_value *out)';
                $lines[] = '{';
                $lines[] = '    /* '.$this->describe($metric, 'out->').' */';
                $lines[] = '    (void)device_id;';
                $lines[] = '    (void)out;';
                $lines[] = '    return FIELD_UNAVAILABLE;';
                $lines[] = '}';
                if ($metric['writable']) {
                    $lines[] = '';
                    $lines[] = 'field_status field_command_'.$metric['function'].'(const char *device_id, const iotos_value *value)';
                    $lines[] = '{';
                    $lines[] = '    /* '.$this->describe($metric, 'value->').' Apply it, then return FIELD_OK. */';
                    $lines[] = '    (void)device_id;';
                    $lines[] = '    (void)value;';
                    $lines[] = '    return FIELD_REJECTED;';
                    $lines[] = '}';
                }
            }
        }
        $lines[] = '';
        $lines[] = '/* main.c calls these two. */';
        array_push($lines, ...$this->dispatcher($sections, 'read', 'iotos_value *out', 'out', 'FIELD_UNAVAILABLE', fn () => true));
        array_push($lines, ...$this->dispatcher($sections, 'command', 'const iotos_value *value', 'value', 'FIELD_REJECTED', fn (array $metric) => $metric['writable']));

        return implode("\n", $lines)."\n";
    }

    private function dispatcher(array $sections, string $kind, string $parameter, string $argument, string $fallback, callable $include): array
    {
        $lines = ['', 'field_status field_'.$kind.'(const char *type, const char *metric, const char *device_id, '.$parameter.')', '{'];
        $branches = 0;
        foreach ($sections as $section) {
            $metrics = array_values(array_filter($section['metrics'], $include));
            if ($metrics === []) {
                continue;
            }
            $lines[] = '    if (strcmp(type, '.$this->tables->string($section['type']['code']).') == 0) {';
            foreach ($metrics as $metric) {
                $lines[] = '        if (strcmp(metric, '.$this->tables->string($metric['key']).') == 0) {';
                $lines[] = '            return field_'.$kind.'_'.$metric['function'].'(device_id, '.$argument.');';
                $lines[] = '        }';
                $branches++;
            }
            $lines[] = '    }';
        }
        if ($branches === 0) {
            array_push($lines, '    (void)type;', '    (void)metric;', '    (void)device_id;', '    (void)'.$argument.';');
        }
        $lines[] = '    return '.$fallback.';';
        $lines[] = '}';

        return $lines;
    }

    private function describe(array $metric, string $prefix): string
    {
        $text = $metric['key'].': '.$metric['datatype'].($metric['unit'] !== null ? ' in '.$metric['unit'] : '').', '.$prefix.self::MEMBERS[$metric['datatype']].'.';
        if ($metric['enum_values'] !== null) {
            $text .= ' One of: '.implode(', ', $metric['enum_values']).'.';
        }
        if ($metric['min'] !== null || $metric['max'] !== null) {
            $text .= ' Range '.($metric['min'] ?? '...').' to '.($metric['max'] ?? '...').'.';
        }

        return $this->tables->comment($text);
    }

    private function example(array $type): string
    {
        return substr($type['code'], 0, 12).'-1';
    }

    /** An annotated device brief for these profiles, valid against the schema, with every fact unknown. */
    private function brief(array $sections, bool $gateway): string
    {
        $lines = [
            '# An example device brief for this starter. The coding agent writes device-brief.yaml next to',
            '# this file from the interview in AGENTS.md, checks it against .iotos/device-brief.schema.json',
            '# and asks you to confirm it before writing any code. "unknown" is allowed for any fact.',
            'format: 1',
            'device:',
            '  board: unknown              # such as ESP32-DevKitC or i.MX RT1050 EVKB',
            '  mcu: unknown',
            '  framework: unknown          # such as ESP-IDF, MCUXpresso with FreeRTOS, or Linux',
            '  framework_version: unknown',
            '  memory_notes: ""',
            'uplink:',
            '  kind: unknown               # ethernet, wifi, cellular_modem or other',
            '  modem_runs_mqtt: unknown    # true when a cellular modem runs TLS and MQTT itself',
            'time_source: unknown          # sntp, modem, gps or rtc',
            'credential_storage: unknown   # compiled, flash or secure_element',
            'device_types:',
        ];
        foreach ($sections as $section) {
            $type = $section['type'];
            $lines[] = '  '.$type['code'].':'.str_repeat(' ', max(1, 27 - strlen($type['code']))).'# '.$this->yamlComment($type['name'].', revision '.$type['revision']);
            $lines[] = '    addressing:';
            $lines[] = '      bus: unknown             # modbus_rtu, modbus_tcp, i2c, spi, can, gpio, analog, none or other';
            if (! $section['node']) {
                $lines[] = '      addresses: unknown       # a list such as [1, 2], or a range such as "1-16"';
                $lines[] = '      device_id_pattern: unknown # how each device ID is formed, such as '.$this->example($type);
            }
            $lines[] = '    poll_interval_s: unknown';
            $lines[] = '    report:';
            $lines[] = '      mode: unknown            # on_change (with a deadband) or interval (with interval_s)';
            if (! $section['node']) {
                $lines[] = '    offline_after:';
                $lines[] = '      missed_polls: unknown';
            }
            $lines[] = '    metrics:';
            foreach ($section['metrics'] as $metric) {
                $lines[] = '      '.$this->yamlKey($metric['key']).':'.str_repeat(' ', max(1, 23 - strlen($this->yamlKey($metric['key'])))).'# '.$this->yamlComment($metric['datatype'].($metric['unit'] !== null ? ', '.$metric['unit'] : '').($metric['writable'] ? ', accepts commands' : ''));
                $lines[] = '        source: {kind: unknown}  # modbus, analog, digital, i2c, spi, can, pulse or computed';
            }
            $writable = array_values(array_filter($section['metrics'], fn (array $metric): bool => $metric['writable']));
            if ($writable !== []) {
                $lines[] = '    commands:';
                foreach ($writable as $metric) {
                    $lines[] = '      '.$this->yamlKey($metric['key']).':';
                    $lines[] = '        effect: unknown        # what happens physically';
                    $lines[] = '        read_back: unknown     # how the new state is read back';
                }
            }
        }
        array_push($lines,
            'power:',
            '  mode: unknown               # mains, battery, solar or other',
            'watchdog:',
            '  enabled: unknown',
            'instructions: ""              # wiring, calibration, quirks',
            'unconfirmed: []               # answers not yet proved by a reading',
        );

        return implode("\n", $lines)."\n";
    }

    private function yamlKey(string $key): string
    {
        return preg_match('/^[A-Za-z][A-Za-z0-9_-]*$/', $key) === 1 ? $key : '"'.$key.'"';
    }

    private function yamlComment(string $text): string
    {
        return (string) preg_replace('/[\x00-\x1f\x7f]/', ' ', $text);
    }
}
